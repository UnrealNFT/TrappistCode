import ollama

MODELE_CERVEAU = "hf.co/mradermacher/DeepSeek-V4-Pro-Qwen3.5-9B-UNCENSORED-heretic-i1-GGUF:Q4_K_M"
MODELE_RELECTEUR = "huihui_ai/qwen3-abliterated:8b"

SYSTEM_CERVEAU = """You are an expert in structured reasoning.
Analyze the request thoroughly, break it down into clear steps, and provide a complete and well-argued answer.
If code is needed, write it clearly."""

SYSTEM_RELECTEUR = """You are a critical reviewer. You are given a question and an answer generated by another model.

Your mission:
1. Check logical and factual consistency
2. Correct any errors or inaccuracies
3. Improve clarity and structure
4. Add clear comments in French
5. Provide a clean and improved final version

If the answer is already good, say so and do not invent problems."""

def cerveau(question: str) -> str:
    try:
        response = ollama.chat(
            model=MODELE_CERVEAU,
            messages=[
                {"role": "system", "content": SYSTEM_CERVEAU},
                {"role": "user", "content": question}
            ]
        )
        return response["message"]["content"]
    except Exception as e:
        return f"Erreur cerveau: {e}"

def relecteur(question: str, reponse: str) -> str:
    prompt = f"""Original question:
{question}

Answer from the first model:
{reponse}

---
Review the answer, correct it if needed, and comment the code in French.
Provide a clean final version."""

    try:
        response = ollama.chat(
            model=MODELE_RELECTEUR,
            messages=[
                {"role": "system", "content": SYSTEM_RELECTEUR},
                {"role": "user", "content": prompt}
            ]
        )
        return response["message"]["content"]
    except Exception as e:
        return f"Erreur relecteur: {e}"

if __name__ == "__main__":
    question = input("Question : ")
    
    print("\n=== Reasoning (DeepSeek) ===")
    reponse_deepseek = cerveau(question)
    print(reponse_deepseek)
    
    print("\n=== Final version (Qwen) ===")
    version_finale = relecteur(question, reponse_deepseek)
    print(version_finale)
    